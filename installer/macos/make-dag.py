#!/usr/bin/env python3
"""Write the installer's Dagu workflow (D35) from the template's pinned tools.

One step per tool of template/mise.toml.jinja, so the installer window can show each
dependency installing. Parameters arrive as environment variables (never interpolated
into the command line). Usage: make-dag.py <template/mise.toml.jinja> <out.yaml>
"""
import re
import sys

source, out = sys.argv[1], sys.argv[2]
text = open(source).read()
block = re.search(r"^\[tools\]\n(.*?)(?:^\[|\Z)", text, re.S | re.M).group(1)
tools = re.findall(r'^"?([^"=\s]+)"?\s*=\s*"([^"]+)"', block, re.M)
if not tools:
    sys.exit("no [tools] found in " + source)


def step_id(tool):
    # Dagu step ids: ^[a-zA-Z][a-zA-Z0-9_]*$
    return "tool_" + re.sub(r"[^a-z0-9]+", "_", tool.split(":")[-1].split("/")[-1].lower()).strip("_")


lines = [
    "# Generated by installer/macos/make-dag.py from template/mise.toml.jinja. Do not edit.",
    "description: Create and start a Fyso project (macOS installer, D35)",
    "type: graph",
    "params:",
    "  - DIR: \"\"        # absolute path of the new project folder (must not exist)",
    "  - NAME: \"\"",
    "  - SLUG: \"\"",
    "  - PORT: \"8400\"",
    "  - ENGINE: claude",
    "  - SOURCE: gh:fyso-dev/agentic-framework",
    "  - REF: main",
    "  - MISE: \"\"       # absolute path of the mise binary",
    "  - GIT_NAME: \"\"",
    "  - GIT_EMAIL: \"\"",
    "env:",
    "  - MISE_YES: \"1\"",
    "steps:",
    "  - id: generate",
    "    run: >-",
    "      \"$MISE\" exec aqua:astral-sh/uv@0.5.1 -- uvx --from copier==9.19.1 copier copy --trust --defaults",
    "      --vcs-ref \"$REF\" --data project_name=\"$NAME\" --data project_slug=\"$SLUG\"",
    "      --data port_base=\"$PORT\" --data engine=\"$ENGINE\" \"$SOURCE\" \"$DIR\"",
    "  - id: trust",
    "    run: cd \"$DIR\" && \"$MISE\" trust",
    "    depends: [generate]",
]
node = next((step_id(t) for t, _ in tools if t == "core:node"), None)
ids = []
for tool, version in tools:
    sid = step_id(tool)
    ids.append(sid)
    deps = ["trust"] + ([node] if tool.startswith("npm:") and node else [])
    lines += [
        f"  - id: {sid}",
        f"    run: cd \"$DIR\" && \"$MISE\" install \"{tool}@{version}\"",
        f"    depends: [{', '.join(deps)}]",
    ]
lines += [
    "  - id: git",
    "    run: >-",
    "      cd \"$DIR\" && git init -q -b main &&",
    "      { git config user.name >/dev/null || git config user.name \"$GIT_NAME\"; } &&",
    "      { git config user.email >/dev/null || git config user.email \"$GIT_EMAIL\"; } &&",
    "      git add . && git commit -q -m \"chore: initialize Fyso project\"",
    "    depends: [generate]",
    "  - id: setup",
    "    run: cd \"$DIR\" && \"$MISE\" run setup",
    f"    depends: [git, {', '.join(ids)}]",
    "  - id: start",
    "    run: cd \"$DIR\" && \"$MISE\" run up",
    "    depends: [setup]",
]
open(out, "w").write("\n".join(lines) + "\n")
print(" ".join(ids))

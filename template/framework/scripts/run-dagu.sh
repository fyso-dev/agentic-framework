#!/usr/bin/env bash
# Dagu for this project only: own home, own ports, localhost, basic auth (D19).
set -euo pipefail
source "$(dirname "$0")/lib.sh"
require_env FYSO_DATA FYSO_ROOT FYSO_ADMIN_USER FYSO_ADMIN_PASSWORD FYSO_DAGU_PORT FYSO_OMB_PORT OPENMAUSBOT_URL
mkdir -p "$FYSO_DATA/dagu"
# Workflow steps and harness.run execute agent code: Dagu runs confined (D93). Inside,
# the age key paths below point at the project's own key.
confined_exec \
  DAGU_HOME="$FYSO_DATA/dagu" \
  DAGU_UI_NAVBAR_TITLE="$(node "$FYSO_ROOT/framework/scripts/brand.cjs" title)" \
  DAGU_DAGS_DIR="$FYSO_ROOT/project/workflows" \
  DAGU_WIKI_DIR="$FYSO_ROOT/project/wiki" \
  DAGU_HOST=127.0.0.1 \
  DAGU_PORT="$FYSO_DAGU_PORT" \
  DAGU_SCHEDULER_PORT="$FYSO_DAGU_SCHEDULER_PORT" \
  DAGU_WORKER_HEALTH_PORT="$FYSO_DAGU_WORKER_HEALTH_PORT" \
  DAGU_COORDINATOR_HOST=127.0.0.1 \
  DAGU_COORDINATOR_PORT="$FYSO_DAGU_COORDINATOR_PORT" \
  DAGU_COORDINATOR_HEALTH_PORT="$FYSO_DAGU_COORDINATOR_HEALTH_PORT" \
  DAGU_PEER_INSECURE=true \
  DAGU_DAG_DISCOVERY_SYMLINKS=true \
  DAGU_ENV_PASSTHROUGH_PREFIXES=FYSO_,OPENMAUSBOT_,ALLOW_INSECURE_HTTP,MISE_DATA_DIR,MISE_CACHE_DIR,MISE_STATE_DIR,MISE_TRUSTED_CONFIG_PATHS,MISE_SOPS_AGE_KEY_FILE,SOPS_AGE_KEY_FILE,CLAUDE_CONFIG_DIR,CODEX_HOME,PI_CODING_AGENT_DIR \
  FYSO_COMPOSIO_AGE_KEY_FILE="${MISE_SOPS_AGE_KEY_FILE:-${SOPS_AGE_KEY_FILE:-$HOME/.config/mise/age.txt}}" \
  FYSO_PROJECT="$FYSO_PROJECT" FYSO_HTTP_PORT="$FYSO_HTTP_PORT" \
  FYSO_DAGU_PORT="$FYSO_DAGU_PORT" FYSO_ADMIN_USER="$FYSO_ADMIN_USER" FYSO_ADMIN_PASSWORD="$FYSO_ADMIN_PASSWORD" \
  FYSO_ROOT="$FYSO_ROOT" FYSO_DATA="$FYSO_DATA" FYSO_OMB_PORT="$FYSO_OMB_PORT" \
  OPENMAUSBOT_URL="$OPENMAUSBOT_URL" ALLOW_INSECURE_HTTP=true \
  DAGU_AUTH_MODE=basic \
  DAGU_AUTH_BASIC_USERNAME="$FYSO_ADMIN_USER" \
  DAGU_AUTH_BASIC_PASSWORD="$FYSO_ADMIN_PASSWORD" \
  dagu start-all
